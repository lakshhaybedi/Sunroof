import AppKit
import Testing
@testable import Sunroof

@MainActor
@Suite struct ClipReaderTests {
    let box = TestPasteboard()
    var pb: NSPasteboard { box.pb }
    let dir = tempDir()
    let source = ClipSource(bundleID: "com.apple.TextEdit", name: "TextEdit")

    func read(_ apps: [String: SensitiveMode] = [:]) -> Clip? {
        ClipReader.read(pb, source: source, imagesDir: dir, sensitiveApps: apps)
    }

    @Test func plainText() {
        pb.setString("hello", forType: .string)
        let c = read()
        #expect(c?.kind == .text)
        #expect(c?.text == "hello")
        #expect(c?.source == source)
    }

    @Test func richTextKeepsRTF() {
        pb.declareTypes([.string, .rtf], owner: nil)
        pb.setString("hi", forType: .string)
        pb.setData(NSAttributedString(string: "hi").rtf(from: NSRange(location: 0, length: 2)), forType: .rtf)
        let c = read()
        #expect(c?.kind == .richText)
        #expect(c?.rtf != nil)
        #expect(c?.text == "hi")
    }

    @Test func urlString() {
        pb.setString("https://unclutterapp.com/panels/clipboard/", forType: .string)
        #expect(read()?.kind == .url)
    }

    @Test func textWithSpacesIsNotURL() {
        pb.setString("see https://x.com now", forType: .string)
        #expect(read()?.kind == .text)
    }

    @Test func fileURLs() {
        pb.writeObjects([URL(fileURLWithPath: "/tmp/a.txt") as NSURL])
        let c = read()
        #expect(c?.kind == .files)
        #expect(c?.fileURLs == [URL(fileURLWithPath: "/tmp/a.txt")])
        #expect(c?.text == "a.txt")
    }

    @Test func pngImageSaved() throws {
        pb.setData(pngData(width: 4, height: 4), forType: .png)
        let c = try #require(read())
        #expect(c.kind == .image)
        let file = try #require(c.imageFile)
        #expect(FileManager.default.fileExists(atPath: dir.appendingPathComponent(file).path))
    }

    @Test func textBeatsImage() {
        pb.declareTypes([.string, .tiff], owner: nil)
        pb.setString("words", forType: .string)
        pb.setData(NSImage(data: pngData(width: 4, height: 4))!.tiffRepresentation, forType: .tiff)
        #expect(read()?.kind == .text)
    }

    @Test func colour() {
        pb.writeObjects([NSColor(srgbRed: 1, green: 0, blue: 0, alpha: 1)])
        let c = read()
        #expect(c?.kind == .color)
        #expect(c?.text == "#FF0000")
    }

    func withMarker(_ type: String) -> Clip? {
        pb.declareTypes([.string, .init(type)], owner: nil)
        pb.setString("x", forType: .string)
        pb.setData(Data(), forType: .init(type))
        return read()
    }

    @Test func ownMarkerIgnored() { #expect(withMarker("com.lakshhaybedi.Sunroof.own") == nil) }
    @Test func transientIgnored() { #expect(withMarker("org.nspasteboard.TransientType") == nil) }
    @Test func autoGeneratedIgnored() { #expect(withMarker("org.nspasteboard.AutoGeneratedType") == nil) }
    @Test func concealedIsSensitive() { #expect(withMarker("org.nspasteboard.ConcealedType")?.isSensitive == true) }

    @Test func appIgnoreList() {
        pb.setString("secret", forType: .string)
        #expect(read(["com.apple.TextEdit": .ignore]) == nil)
    }

    @Test func appConcealList() {
        pb.setString("secret", forType: .string)
        #expect(read(["com.apple.TextEdit": .conceal])?.isSensitive == true)
    }

    @Test func emptyStringIgnored() {
        pb.setString("   ", forType: .string)
        #expect(read() == nil)
    }

    @Test func hugeTextIgnored() {
        pb.setString(String(repeating: "a", count: 1_000_001), forType: .string)
        #expect(read() == nil)
    }

    @Test func sameContentSameHash() {
        pb.setString("hello", forType: .string)
        let a = read()
        let b = read()
        pb.clearContents()
        pb.setString("hello!", forType: .string)
        let c = read()
        #expect(a?.contentHash == b?.contentHash)
        #expect(a?.contentHash != c?.contentHash)
    }

    // Review I2: oversized RTF is dropped; the clip is kept as plain text.
    @Test func hugeRTFStoredAsPlainText() {
        pb.declareTypes([.string, .rtf], owner: nil)
        pb.setString("hi", forType: .string)
        pb.setData(Data(count: 2_000_001), forType: .rtf)
        let c = read()
        #expect(c?.kind == .text)
        #expect(c?.rtf == nil)
    }

    // Review I3: a huge TIFF is rejected before it is decoded and converted.
    @Test func hugeTIFFIgnored() {
        let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 3000, pixelsHigh: 2000, bitsPerSample: 8,
                                   samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
                                   bytesPerRow: 0, bitsPerPixel: 0)!
        pb.setData(rep.tiffRepresentation, forType: .tiff) // ~24 MB uncompressed
        #expect(read() == nil)
    }
}
