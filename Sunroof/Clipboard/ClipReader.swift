import AppKit

/// Turns the current pasteboard contents into a `Clip`, or nil when it shouldn't be recorded.
enum ClipReader {
    static let ownType = NSPasteboard.PasteboardType("com.lakshhaybedi.Sunroof.own")
    // Caps keep 50 clips inside the §8 memory budget.
    static let maxTextBytes = 1_000_000
    static let maxRTFBytes = 2_000_000   // larger RTF: keep the clip as plain text
    static let maxImageBytes = 20_000_000

    // nspasteboard.org markers used by password managers and utilities.
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let urlSchemes: Set<String> = ["http", "https", "file", "mailto"]

    static func read(_ pb: NSPasteboard, source: ClipSource, imagesDir: URL,
                     sensitiveApps: [String: SensitiveMode], now: Date = .now) -> Clip? {
        let types = Set(pb.types ?? [])
        if !types.isDisjoint(with: [ownType, transient, autoGenerated]) { return nil }
        let appMode = source.bundleID.flatMap { sensitiveApps[$0] }
        if appMode == .ignore { return nil }
        let sensitive = types.contains(concealed) || appMode == .conceal

        func clip(_ kind: ClipKind, payload: Data, text: String? = nil) -> Clip {
            Clip(kind: kind, date: now, text: text, source: source,
                 contentHash: Clip.hash(kind: kind, payload: payload), isSensitive: sensitive)
        }

        if types.contains(.fileURL),
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            var c = clip(.files, payload: Data(urls.map(\.path).joined(separator: "\n").utf8),
                         text: urls.map(\.lastPathComponent).joined(separator: "\n"))
            c.fileURLs = urls
            return c
        }

        if types.contains(.color), let color = NSColor(from: pb)?.usingColorSpace(.sRGB) {
            let hex = String(format: "#%02X%02X%02X", Int(round(color.redComponent * 255)),
                             Int(round(color.greenComponent * 255)), Int(round(color.blueComponent * 255)))
            return clip(.color, payload: Data(hex.utf8), text: hex)
        }

        if let string = pb.string(forType: .string) {
            guard string.utf8.count <= maxTextBytes,
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
            if isURL(string) { return clip(.url, payload: Data(string.utf8), text: string) }
            if let rtf = pb.data(forType: .rtf), rtf.count <= maxRTFBytes {
                var c = clip(.richText, payload: Data(string.utf8), text: string)
                c.rtf = rtf
                return c
            }
            return clip(.text, payload: Data(string.utf8), text: string)
        }

        // ponytail: sensitive images are dropped — password managers copy text; add in-memory images if ever needed
        guard !sensitive, let png = pngData(pb), png.count <= maxImageBytes else { return nil }
        var c = clip(.image, payload: png)
        let name = "\(c.id.uuidString).png"
        guard (try? png.write(to: imagesDir.appendingPathComponent(name), options: .atomic)) != nil else { return nil }
        c.imageFile = name
        return c
    }

    private static func isURL(_ s: String) -> Bool {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.contains(where: \.isWhitespace), let url = URL(string: t), let scheme = url.scheme?.lowercased()
        else { return false }
        return urlSchemes.contains(scheme)
    }

    private static func pngData(_ pb: NSPasteboard) -> Data? {
        if let png = pb.data(forType: .png) { return png }
        // Reject before decoding: converting a huge TIFF is slow and memory-hungry.
        guard let tiff = pb.data(forType: .tiff), tiff.count <= maxImageBytes,
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}
